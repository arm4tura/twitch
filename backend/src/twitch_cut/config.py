        # 200, а не 300: на записях этого уровня (15 и 25 минут) первые 200 мс
        # покупают 13 из 15 накрытых окон, а следующие 100 — ещё 2 ценой 6
        # съеденных чистых слов (таблица выше). Уровень по умолчанию берёт
