SPOT_MIN_SCORE = 0.45
"""Порог поиска мата по посториорам CTC: средняя вероятность буквы корня (0..1).

Выбран по замеру на реальном прогоне (15 минут стрима, правки человека как
истина), а не на глаз. Кривая порога при `require_unheard=True` и разрыве до 6
кадров, где NEW — мат, которого текстовый детектор не нашёл, а человек добавил
руками, FP — кандидат, которому человек мьют не ставил:

    0.30 → NEW 1, FP 4      0.45 → NEW 1, FP 1
    0.40 → NEW 1, FP 1      0.55 → NEW 0, FP 0

Ниже 0.45 растут только ложные, выше 0.50 теряется единственная настоящая
находка («ебан» со скором 0.54 там, где ASR услышал «епанисир»). Честная цена
стадии: примерно одна новая находка и один лишний кандидат на 15 минут — потому
кандидаты и идут в decisions.json как `review`, а не как готовый мьют."""


# =============================================================================
# ЧУВСТВИТЕЛЬНОСТЬ — одна ручка вместо россыпи чисел
#
# Все значения ниже — про ОДИН выбор: что дороже, слышимый мат или лишняя
# замьюченная речь. Пока они лежали отдельными константами (да ещё и
# продублированными в CLI и в схеме API), этот выбор нельзя было сделать: чтобы
# «глушить чуть шире», надо было знать, что padding, склейку и поджим по RMS
# двигают в одну сторону, а порог спотинга — в другую.
#
# Поэтому наружу выходит ОДИН параметр `sensitivity`, а числа выводятся из него.
# Уровень `balanced` — ровно то, что стояло в дефолтах до появления ручки, и это
# не «золотая середина по вкусу», а единственная измеренная точка (см. замеры в
# SPOT_MIN_SCORE и mute_refine). Соседние уровни — один шаг в известную сторону,
# и все три измерены на том же 15-минутном прогоне (правки человека как истина,
# транскрипт и посториоры из кэша, счёт — `tools/sensitivity_levels.py`):
#
#              мьютов  попали  лишние  проп   F1   накрыто  дырка  лишнего
#   low          154     137      17    16   0.888   9/142  110мс   15.6с
#   balanced     154     140      14    13   0.909  30/142   86мс   17.5с
#   high         154     140      14    13   0.909  36/142   78мс   20.9с
#
# «накрыто» — сколько мьютов человека заглушены ЦЕЛИКОМ, «дырка» — медиана
# незаглушенного остатка внутри его окна, «лишнего» — сумма мьюта вне его окон.
#
# Читается так, и это важнее самих чисел: F1 выше `balanced` не растёт (шаг в
# `high` не даёт ни одного нового попадания), а покупается на самом деле накрытие
# — 9 → 30 → 36 окон целиком и остаток 110 → 78 мс, ценой 15.6 → 20.9 секунды
# лишнего мьюта на 15 минут. Именно поэтому ручка одна и называется «что дороже»,
# а не «качество»: слышимый хвост мата виден в накрытии, а не в F1, и цену за него
# платит чистая речь. Шаг в `low` — единственный, который теряет и то и другое
# (3 попадания и 21 полное накрытие), так что дефолт `balanced` не случаен.
#
# Замер по ходу вскрыл ещё одно: `mute_join_gap_ms` на этом корпусе НЕ работает —
# склеенных групп ровно 8 при 300, 600 и 900 мс. Он остаётся в уровне (шаг в ту же
# сторону, что padding), но улучшений от него не ждать: соседние маты либо
# вплотную, либо дальше секунды.
#
# СЕДЬМОЕ ЧИСЛО — `mute_expand_on_silence_ms` — появилось позже и замерено
# отдельно: на четырёх правленых записях (5 и 10 минут — `high`, 15 и 25 —
# `balanced`), пересборкой окон настоящим `build_decisions` из тех же кэшей.
# Это единственная операция, которая делает окно ШИРЕ, и платит она тем же —
# лишним мьютом. «Накрыто» — окон человека заглушено целиком, «съедено» — целых
# чистых слов проглочено мьютом:
#
#                накрыто целиком          съедено чистых слов      мьюта, с
#   запись     0 → 200 → 300 → 500      0 → 200 → 300 → 500      0 → 300
#   10 мин   54 → 56 → 57 → 58  /74   13 → 23 → 25 → 34       34.1 → 42.0
#   15 мин   16 → 27 → 29 → 31 /142    3 → 15 → 19 → 33       45.5 → 56.7
#   25 мин   28 → 30 → 30 → 31  /78    1 →  2 →  4 →  6       30.9 → 34.2
#   5 мин    29 → 29 → 29 → 29  /34    6 →  8 →  8 →  8       17.1 → 18.3
#
# Читается так: первые 200 мс покупают 15 накрытых окон из 18 по цене 1.5
# съеденного слова за окно, следующие 100 мс — ещё 3 по 2.7 слова, а 500 мс —
# ещё 4 по 6.3 слова. Поэтому кривая режется по уровням: `low` — 0, `balanced` —
# 200, `high` — 300. На 5 минутах прироста нет ВООБЩЕ ни при каком значении, и
# это не шум: из четырёх непокрытых окон там три стоят на звуке (вердикт `ok`,
# расширение к ним не относится), а четвёртому звук идёт ПОЗЖЕ разметки —
# расширение назад его не достаёт.
#
# Чего расширение не лечит (замерено на тех же четырёх записях). После него
# остаётся 63 непокрытых окна человека, и у 52 из них вердикт `ok` — в окне есть
# звук, просто не тот: сетка слов сдвинута на 200–600 мс (чаще ПОЗЖЕ — emission
# delay CTC), а мат звучит рядом внутри того же непрерывного звонкого участка.
# Растянуть окно на весь задетый участок не помогает: +41 мс медианно и 0 из 29
# окон человека накрылось бы целиком. То есть геометрией энергии этот класс не
# берётся — там нужна другая сетка слов, а не другой порог по звуку.
#
# ВОСЬМОЕ ЧИСЛО — `mute_head_cross_prev_ms` — про то, почему `padding_before` был
# бездействующим. Головной отступ клампился концом предыдущего слова, а сетка ASR
# в связной речи идёт вплотную, поэтому 140 мс `high` схлопывались в ноль ровно
# там, где человек потом расширял голову руками. Допуск снимает клэмп, но не
# больше чем на сам padding.
#
# ЧЕМ ЭТО ЧИСЛО МЕРИЛОСЬ РАНЬШЕ И ПОЧЕМУ ЭТО БЫЛО НЕВЕРНО. Линейка «слышно» —
# кадры 10 мс внутри окна человека, где звук громче порога и НЕ накрыт машиной —
# считает только НЕДОКРЫТИЕ (мат слышен) и СТРУКТУРНО слепа к обратной ошибке:
# замьюченной ЧИСТОЙ речи соседа. Поэтому каждый её прогон мог только ПОДНИМАТЬ
# допуск, и так `high` дополз до 100. Но в связной речи `prev_word_end ≈ onset`,
# так что эти 100 мс — не мат, а хвост чистого соседнего слова, и поджим по RMS
# его не снимает (он звонкий). Ровно на это жаловался пользователь: правит одно и
# то же окно за окном, а ему опять «подвинь на 100 мс».
#
# ЧЕСТНЫЙ ДВУСТОРОННИЙ ЗАМЕР. tools/head_sweep.py пересобирает окна настоящим
# `build_decisions` из тех же кэшей (сборка при cross=100/страж=off совпадает с
# journal.baseline записи БАЙТ-В-БАЙТ — проверка верности) и на ВОСЬМИ правленых
# человеком записях меряет обе стороны: недокрытие (полнота/полнота_поиска по
# пересечению и зазору) И переглушку (голова = сколько машина начала РАНЬШЕ
# границы человека). На записи-жалобе (vod_2848854199, high) при cross=100:
#
#   голова переглушки: 6.58 с (медиана 141 мс на 40 окнах из 75)
#
# — вот те самые ручные правки, которые линейка «слышно» не видела вовсе.
#
# ЧТО ЧИНИТ ПРОБЛЕМУ (а не симптом): страж по звуку `mute_head_cross_voiced_guard`
# (ниже, дефолт вкл). Голове разрешено зайти на соседа ТОЛЬКО по тишине — на
# первом звонком кадре допуск обрубается. По записи это ПОКАДРОВОЕ решение, а не
# одно число на весь корпус. Замер cross=100, страж off→on:
#
#   голова переглушки по корпусу (8 записей):  67.2 → 49.9 с  (−26%)
#   запись-жалоба:  6.58 → 3.58 с, медиана 141 → 70 мс, точность/полнота/полнота_
#                   поиска не шелохнулись (0.987 / 1.000 / 1.000) — чистый выигрыш
#
# Тупо занулить cross нельзя: cross=0 роняет полноту (1.000 → 0.987 на жалобе) —
# на записях с настоящей паузой перед матом допуск нужен, чтобы достать поздний
# onset. Страж и сохраняет его там (по тишине), и схлопывает на связной речи.
# На ТРЁХ записях страж роняет полноту ПО ПЕРЕСЕЧЕНИЮ (0423, 1841, 2845916736):
# там человек расширил голову в ЗВОНКОГО соседа, где стоит пропущенный детектором
# мат (`выебала блять`) — но полнота_поиска по зазору при этом НЕ падает нигде,
# то есть ни одно окно человека не брошено. Эти случаи — работа ДЕТЕКЦИИ, их
# нельзя покупать мьютом чистой звонкой речи (см. маршрут в review, decisions.py).
#
# ПОЧЕМУ ТЕПЕРЬ `high` = 60, А НЕ 100. Со стражем cross ∈ {60,100,140} на восьми
# записях неразличимы (полнота и голова совпадают до сотых — страж режет тишину
# одинаково при любом потолке). Разница видна ТОЛЬКО когда страж выключен
# (`raw_mute` или нет аудио): там 100 переглушает вдвое сильнее 60. Значит потолок
# ставим по самому безопасному нестражённому запасному ходу — 60 (= `balanced`).
# Агрессивность `high` живёт в детекции (padding, spot_min_score, расширение), а
# не в заходе глубже на чистого соседа. Выше 140 бессмысленно: упор в padding.
#
# Допуск конкурирует с расширением на тишине, и это тоже замерено: зайдя на
# соседа, голова задевает его звук, вердикт «стоит на тишине» становится `ok` и
# расширение на 300 мс не срабатывает — 60 мс отменяют 380. Обратный порядок
# («судить вердикт по окну без допуска») прогнан и ПРОИГРАЛ: вердикт возвращается
# 7 → 10 окон на 10 минутах, утечка при этом 1.56 → 1.55 с, а съеденных чистых
# слов +5. Если допуск уже достал до звука, посылка расширения («звука в окне нет
# вовсе») ложна. Страж ЭТОГО выбора (не путать со стражем по звуку) —
# tests/test_mute_refine.py::
# test_head_allowance_can_switch_the_expansion_off_and_that_is_measured, где
# `mute_head_cross_voiced_guard=False` держит именно этот размен в изоляции.
# =============================================================================
