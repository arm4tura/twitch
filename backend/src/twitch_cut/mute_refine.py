REANCHOR_MAX_VOICED = 0.2
# Короче этого участок речи не считается словом: 100 мс — нижняя граница
# длительности слога, всё что короче это щелчки, вдохи и стуки по столу.
REANCHOR_MIN_RUN_MS = 100
# Дальше этого зазора тишины окно не переносится (когда перенос вообще включён):
