# Шаг анализа энергии, мс. 10 мс — стандартный кадр для речи: короче нет смысла
# (пик внутри периода основного тона), длиннее — граница «плывёт» на десятки мс.
FRAME_MS = 10
# Сколько слушаем ВОКРУГ окна, мс. Нужно, чтобы оценить шумовой пол: окно из
# одной сплошной речи своей тишины не содержит, и без запаса пол пришлось бы
# выдумывать.
MARGIN_MS = 400
# Перцентиль для шумового пола (по кадрам окна + запаса).
FLOOR_PCT = 0.15
# Порог = max(пик*ratio, пол*FLOOR_MULT), но НЕ выше пика*THR_CAP — иначе на
# шумной записи (высокий пол) порог уехал бы почти в пик и срезал бы речь.
FLOOR_MULT = 2.0
THR_CAP = 0.5
# Пауза, начиная с которой звук в padding считается ЧУЖИМ словом и убирается из
# мьюта (`_gap_cut`). Замерено на четырёх правленых записях (55 минут, 328 окон
# человека); «утечка» — мс звука выше абсолютного порога внутри окон человека,
# оставшегося вне мьютов, «лишнее» — звонкие мс в мьютах, которых человек не
# глушил:
#     пауза      утечка   лишнее   съедено   мьюта
#       0 мс      15.1      16.4       51     155.6
#      40 мс      14.8      17.1       51     158.3
#      60 мс      14.7      17.7       51     159.4
#     100 мс      14.7      17.8       51     160.1
#     не резать   14.7      17.9       51     160.4
# 60 мс — наименьшая пауза, при которой утечка садится на ПОЛ (14.7 с — ровно
# столько же, сколько без поджатия вообще), и при этом лишнего звука на 0.2 с
# меньше, чем если соседа не отдавать никогда. Короче 60 мс порог начинает
# принимать смычку согласного за паузу и отдаёт соседу начало самого мата
# (утечка растёт).
SILENCE_GAP_MS = 60
# Проверка окна на тишину (reanchor_window). Доля озвученных кадров, НЕ ВЫШЕ
# которой окно считается стоящим на тишине. Порог общий с отчётом
# (`audit.on_silence`) — отчёт обязан называть «мьют встал не на звук» ровно там,
# где так же считает обработка.
#
# 0.2 против 0.05 замерено на трёх записях (248 окон, 65 переносов руками),
# мерка — попадает ли метка в окно, которое человек ДЕЙСТВИТЕЛЬНО переносил
# (`sessions[*].changes.mutes.moved` в журнале правок):
#   0.2  — 43 метки, 21 попадание (точность 49%, ловит треть переносов человека);
#   0.05 — 29 меток, 15 попаданий (точность 52%);
#   0.0  — 23 метки, 13 попаданий (точность 57%), и это лезвие: один шумный кадр
#          внутри окна снимает метку целиком.
# Пока метка ДВИГАЛА окно, ложное срабатывание стоило дорого (мьют уезжал с мата),
# и узкий порог был осмыслен. Сейчас метка только зовёт человека — цена ложной
