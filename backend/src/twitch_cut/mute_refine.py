# 220 мс.
REANCHOR_MAX_GAP_MS = 280


class WavEnergy:
    """Ленивый доступ к RMS-огибающей WAV-файла (s16le mono).

    Читаем ТОЛЬКО нужный кусок через `setpos` — кэш аудио пайплайна это
    16 kHz mono wav на весь диапазон (3 часа ≈ 345 МБ), грузить его в память
    целиком ради нескольких сотен окон незачем.
    """

    def __init__(self, path: Path):
        self._wav = wave.open(str(path), "rb")
        if self._wav.getnchannels() != 1 or self._wav.getsampwidth() != 2:
            self._wav.close()
            raise ValueError(
                f"ожидался mono s16 wav, получено "
                f"ch={self._wav.getnchannels()} width={self._wav.getsampwidth()}"
            )
        self.rate = self._wav.getframerate()
        self.total_frames = self._wav.getnframes()

    @property
    def duration_ms(self) -> int:
        if self.rate <= 0:
            return 0
        return int(self.total_frames * 1000 / self.rate)

    def close(self) -> None:
        try:
            self._wav.close()
        except Exception:  # pragma: no cover - закрытие не должно ронять пайплайн
            pass

    def __enter__(self) -> "WavEnergy":
        return self

    def __exit__(self, *exc: object) -> None:
        self.close()

    def rms_frames(self, start_ms: int, end_ms: int) -> tuple[list[float], int]:
        """RMS по кадрам FRAME_MS на участке [start_ms, end_ms).

        Возвращает (значения 0..1, фактический start_ms первого кадра) —
        фактический старт может отличаться от запрошенного, если запрос вылез
        за начало файла.
        """
        if self.rate <= 0 or end_ms <= start_ms:
            return [], max(start_ms, 0)
        step = max(1, int(self.rate * FRAME_MS / 1000))
        s0 = max(0, int(start_ms * self.rate / 1000))
        s1 = min(self.total_frames, int(math.ceil(end_ms * self.rate / 1000)))
        if s1 <= s0:
            return [], int(s0 * 1000 / self.rate)
        self._wav.setpos(s0)
        raw = self._wav.readframes(s1 - s0)
        # array('h') — 16-бит со знаком в порядке хоста; wav тоже little-endian,
        # а big-endian хостов среди наших платформ (mac/win/linux x86|arm) нет.
        samples = array("h")
        samples.frombytes(raw[: len(raw) - (len(raw) % 2)])
        out: list[float] = []
        for i in range(0, len(samples) - step + 1, step):
            acc = 0
            for j in range(i, i + step):
                v = samples[j]
                acc += v * v
            out.append(math.sqrt(acc / step) / 32768.0)
        return out, int(s0 * 1000 / self.rate)


def _percentile(values: list[float], q: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    idx = min(len(ordered) - 1, max(0, int(q * (len(ordered) - 1))))
    return ordered[idx]


def global_threshold(energy: WavEnergy, *, probes: int = 40, probe_ms: int = 700) -> float:
    """Абсолютный порог «тут вообще есть звук» по всему файлу.

    Локальный порог (как в `trim_window`) для этого вопроса не годится: он
    считается от пика САМОГО участка, поэтому в тишине пиком становится шум,
    порог падает под него и «речь» находится в шуме. Поэтому пол и уровень речи
    оцениваем по РЕДКИМ пробам всего файла — это дёшево (40 × 0.7 с вместо
    15 минут) и устойчиво.

    Один порог на пайплайн и на отчёт: `reanchor_window` решает им, стоит ли
    мьют на звуке, а `audit.find_holes` — есть ли звук там, где ASR не дал ни
    одного слова. Раньше он жил в audit.py, и отчёт мог диагностировать то,
    чего пайплайн про себя не знал.
    """
    total = energy.duration_ms
    if total <= 0:
        return 0.0
    step = max(probe_ms, total // max(1, probes))
    sampled: list[float] = []
    for start in range(0, total, step):
        chunk, _ = energy.rms_frames(start, min(total, start + probe_ms))
        sampled.extend(chunk)
    if not sampled:
        return 0.0
    floor = _percentile(sampled, 0.10)
    # 0.98, а не 0.85: если речи в записи мало (пауза, музыка, тишина между
    # фразами), P85 попадает В ТИШИНУ, порог схлопывается в ноль и дыры
    # перестают находиться вообще. Верхний перцентиль устойчив к такой доле.
    loud = _percentile(sampled, 0.98)
    return max(floor * FLOOR_MULT, loud * 0.15)


def silence_before_ms(
    energy: WavEnergy, at_ms: int, max_ms: int, threshold: float
) -> int:
    """Сколько мс НЕПРЕРЫВНОЙ тишины идёт прямо перед `at_ms` (не дальше `max_ms`).

    Вопрос ровно один и тот же, что у головного клэмпа в `_compute_mute_window`:
    можно ли отодвинуть голову мьюта назад от начала мата, не задев звук соседа.
    Идём от `at_ms` назад по кадрам FRAME_MS и считаем тишину (RMS ниже
    абсолютного порога) до первого звонкого кадра — на нём останавливаемся.
    Голове разрешено зайти только в те кадры, которых по этому порогу «нет».

    Порог АБСОЛЮТНЫЙ (`global_threshold`), а не относительный (как в
    `trim_window`), и это принципиально: вопрос здесь про соседнее слово, а не
    про тихий хвост самого мата, и мерить его надо той же меркой, что и «стоит ли
    окно на тишине». Возвращает 0, если прямо перед `at_ms` звук, — тогда голове
    двигаться некуда, и клэмп по соседу срабатывает как встарь."""
    if max_ms <= 0 or threshold <= 0.0 or at_ms <= 0:
        return 0
    start = max(0, at_ms - max_ms)
    frames, _ = energy.rms_frames(start, at_ms)
    if not frames:
        return 0
    silent = 0
    for value in reversed(frames):
        if value >= threshold:
            break
        silent += 1
    return min(max_ms, silent * FRAME_MS)


def _voiced_runs(
    frames: Sequence[float],
    base_ms: int,
    threshold: float,
    *,
    min_ms: int,
) -> list[tuple[int, int]]:
    """Непрерывные участки выше `threshold` длиннее `min_ms` → интервалы в мс."""
    runs: list[tuple[int, int]] = []
    run: int | None = None
    for i, value in enumerate(frames):
        if value >= threshold:
            if run is None:
                run = i
        elif run is not None:
            if (i - run) * FRAME_MS >= min_ms:
                runs.append((base_ms + run * FRAME_MS, base_ms + i * FRAME_MS))
            run = None
    if run is not None and (len(frames) - run) * FRAME_MS >= min_ms:
        runs.append((base_ms + run * FRAME_MS, base_ms + len(frames) * FRAME_MS))
    return runs


def _core_frame_spans(
    cores: Sequence[tuple[int, int]] | None,
    *,
    base_ms: int,
    lo_i: int,
    hi_i: int,
) -> list[tuple[int, int]]:
    """Перевести интервалы слов (мс) в непустые диапазоны кадров внутри окна.

    Слова, чьи тайминги не пересекаются с окном, отбрасываются: считать по ним
    нечего. Если не осталось ни одного — вернётся пустой список, и вызывающий
    ищет речь по всему окну (лучше, чем не поджимать вовсе).
    """
    spans: list[tuple[int, int]] = []
    for core in cores or ():
        core_start = max(lo_i * FRAME_MS + base_ms, min(core[0], core[1]))
        core_end = min(hi_i * FRAME_MS + base_ms, max(core[0], core[1]))
        c_lo = max(lo_i, int((core_start - base_ms) / FRAME_MS))
        c_hi = min(hi_i, int(math.ceil((core_end - base_ms) / FRAME_MS)))
        if c_hi > c_lo:
            spans.append((c_lo, c_hi))
    return spans


def _gap_cut(chunk: Sequence[float], thr: float) -> int:
    """Сколько кадров с НАЧАЛА `chunk` можно отдать соседу: индекс за ПОСЛЕДНЕЙ
    паузой длиной ≥ `SILENCE_GAP_MS`. Ноль — такой паузы нет.

    Пауза этой длины означает, что звук за ней — отдельное акустическое событие
    (соседнее слово, попавшее в padding), а не край того же слова: ошибка
    разметки сдвигает границу, но не вставляет в слово тишину. Внутренние
    смычки согласных короче порога и паузой не считаются.
    """
    gap = max(1, SILENCE_GAP_MS // FRAME_MS)
    cut = 0
    run: int | None = None
    for i, value in enumerate(chunk):
        if value < thr:
            if run is None:
                run = i
        else:
            if run is not None and i - run >= gap:
                cut = i
            run = None
    if run is not None and len(chunk) - run >= gap:
        cut = len(chunk)
    return cut


def trim_window(
    energy: WavEnergy,
    start_ms: int,
    end_ms: int,
    *,
    cores: Sequence[tuple[int, int]] | None = None,
    peak_ratio: float = 0.12,
    guard_ms: int = 40,
    min_ms: int = 150,
) -> tuple[int, int]:
    """Срезать ТИШИНУ по краям [start_ms, end_ms). Всегда возвращает окно
    ВНУТРИ исходного (или само исходное, если срезать нечего/не по чему).

    Правило: от каждого края идём внутрь и срезаем непрерывную тишину до первого
    звука, отступив `guard_ms`. Через звук поджатие не перескакивает — значит
    звук, попавший в padding, остаётся замьюченным, потому что отличить «хвост
    мата за границей разметки» от «начало соседнего слова» в энергии нельзя, а
    разметка врёт на ±160 мс (квартили против независимой линейки).

    `cores` — интервалы САМИХ матерных слов по таймингам ASR (по одному на слово
    группы, без padding). Они делают две вещи:

    1. Дают порог: он считается от пика того слова, к которому примыкает край.
       Порог от пика ВСЕГО окна задирал громкий сосед в padding — мат под ним
       выглядел тишиной, и мьют уезжал на соседа (10 мьютов из 133: «блять»
       6.866–7.105 → 7.075–7.225). Порог от пика всей группы глушил тихое слово
       рядом с громким («сука ебать» — «сука» тише, мьют начинался с «ебать»).
    2. Отделяют своё от чужого: если между краем окна и словом есть пауза
       ≥ `SILENCE_GAP_MS`, звук ПЕРЕД ней — сосед, и он из мьюта убирается
       (`_gap_cut`).

    Внутрь слова поджатие заходит только по тишине — и это обязательно: у слова
    без своих таймингов (`timing_source == "segment_fallback"`, потолок
    `mute_max_word_seconds`) разметка сама по себе плита на 1.5 с, и звук в ней
    занимает 0.45 с.
    """
    if end_ms <= start_ms:
        return start_ms, end_ms

    a_start = max(0, start_ms - MARGIN_MS)
    a_end = end_ms + MARGIN_MS
    frames, base_ms = energy.rms_frames(a_start, a_end)
    if not frames:
        return start_ms, end_ms

    # Индексы кадров, попадающих в САМО окно (пол считаем по всему участку,
    # порог — по ближайшему к краю слову).
    lo_i = max(0, int((start_ms - base_ms) / FRAME_MS))
    hi_i = min(len(frames), int(math.ceil((end_ms - base_ms) / FRAME_MS)))
    if hi_i <= lo_i:
        return start_ms, end_ms

    spans = sorted(_core_frame_spans(cores, base_ms=base_ms, lo_i=lo_i, hi_i=hi_i))
    floor = _percentile(frames, FLOOR_PCT)

    def threshold(span: tuple[int, int] | None) -> float:
        chunk = frames[span[0]:span[1]] if span is not None else frames[lo_i:hi_i]
        peak = max(chunk) if chunk else 0.0
        if peak <= 0.0:
            # На месте слова абсолютная тишина: относительный порог мерить не от
            # чего, остаётся шумовой пол.
            return floor * FLOOR_MULT
        return min(peak * THR_CAP, max(peak * peak_ratio, floor * FLOOR_MULT))

    head_thr = threshold(spans[0] if spans else None)
    tail_thr = threshold(spans[-1] if spans else None)
    # padding до первого слова и после последнего: только там ищется пауза,
    # отделяющая соседа. Без пригодных cores такой области нет.
    head_pad = frames[lo_i:spans[0][0]] if spans else []
    tail_pad = frames[spans[-1][1]:hi_i][::-1] if spans else []

    new_start = start_ms
    scan_from = lo_i + _gap_cut(head_pad, head_thr)
    first = next((i for i in range(scan_from, hi_i) if frames[i] >= head_thr), None)
    if first is not None:
        new_start = max(start_ms, min(base_ms + first * FRAME_MS - guard_ms, end_ms))

    new_end = end_ms
    scan_to = hi_i - _gap_cut(tail_pad, tail_thr)
    last = next((i for i in range(scan_to - 1, lo_i - 1, -1)
                 if frames[i] >= tail_thr), None)
    if last is not None:
        new_end = min(end_ms, max(base_ms + (last + 1) * FRAME_MS + guard_ms, start_ms))

    if new_end <= new_start:
        # Тишина во всём окне: подгонять не по чему, и «поджать в точку» было бы
        # хуже, чем оставить как решил ASR.
        return start_ms, end_ms

    # Слишком короткий мьют звучит щелчком — растягиваем вокруг центра речи,
    # но остаёмся внутри исходного окна.
    if new_end - new_start < min_ms:
        need = min_ms - (new_end - new_start)
        grow_left = min(need // 2, new_start - start_ms)
        new_start -= grow_left
        new_end = min(end_ms, new_end + (need - grow_left))
        if new_end - new_start < min_ms:
            new_start = max(start_ms, new_end - min_ms)

    return int(new_start), int(new_end)


def reanchor_window(
    energy: WavEnergy,
    start_ms: int,
    end_ms: int,
    *,
    threshold: float,
    search_ms: int = 700,
    guard_ms: int = 40,
    min_run_ms: int = REANCHOR_MIN_RUN_MS,
    max_voiced: float = REANCHOR_MAX_VOICED,
    max_gap_ms: int = REANCHOR_MAX_GAP_MS,
    move: bool = False,
) -> tuple[int, int, str]:
    """Найти окно, стоящее на ТИШИНЕ, и (если `move`) перенести его на речь.
    Длительность окна сохраняется. Возвращает `(start_ms, end_ms, вердикт)`:

    * `"ok"` — в окне есть звук (или мерить нечем), окно не тронуто;
    * `"silent"` — окно стоит на тишине, речь рядом есть, но переносить не велено
      (`move=False`): окно не тронуто, вызывающему стоит позвать человека;
    * `"reanchored"` — окно было тишиной, речь нашлась рядом, окно перенесено;
    * `"no_speech"` — окно стоит на тишине, а речи достаточно близко нет: окно
      оставлено как решил ASR, человека тоже стоит позвать.

    Зачем это нужно отдельно от `trim_window`. Поджатие работает внутри окна и
    по определению не может починить окно, стоящее НЕ ТАМ: ни одна его настройка
    не двигает границы за пределы исходных. А тайминги слова у ASR иногда уезжают
    в тишину целиком — и мьют глушит воздух, мат при этом слышен полностью.
    Признак измеримый: доля кадров выше АБСОЛЮТНОГО порога (`global_threshold`) в
    окне около нуля. Относительный порог поджатия так не умеет — в тишине он
    опускается до уровня шума и «находит» в нём речь.

    ПОЧЕМУ ПЕРЕНОС ПО УМОЛЧАНИЮ ВЫКЛЮЧЕН (`move=False`, `mute_reanchor_move`).
    Механизм сделан по одному случаю на 5-минутной записи, где он попал точно
    (±17 мс от руки человека). На двух записях подольше (25 и 15 минут, 248 окон,
    человек правил результат руками) он проиграл: из 25 переносов 10 увели мьют С
    ТОГО звука, который замьютил человек, и только 2 привели на него. Проверено
    три способа зажать, все на тех же двух записях (счёт — сколько окон стоит на
    звуке человека, было 85/78 и 135/142):

    * ставить окно к БЛИЖНЕЙ стороне участка речи (слева — по её концу) вместо
      начала участка: 84 и 134, то есть ХУЖЕ. Гипотеза «окно уезжает к началу
      длинной реплики» замером не подтвердилась;
    * `max_gap_ms` — переносить только через короткую тишину: 86 и 139. Лучшее из
      всего, что двигает окно, и потому оставлено в силе;
    * «окно пусто относительно своей окрестности» (пик в окне против местного
      шумового пола) как замена триггеру: у настоящего случая отношение 40, у
      вредных 2…640 — разделяющей границы нет.

    Выключенный перенос даёт 86 и 141 — больше любого варианта с переносом.
    Причина в триггере, а не в выборе места: абсолютный порог снят по всему файлу
    и равен уровню громкой речи, поэтому ТИХИЙ мат под ним выглядит тишиной. В
    20 срабатываниях из 25 окно уже стояло на том звуке, который замьютил человек.
    Двигать его было нечего.

    Что осталось от механизма: он ЗАМЕЧАЕТ пустое окно и зовёт человека
    (`"silent"`/`"no_speech"` → `needs_review`). Это измеримо полезно: на трёх
    записях метка встала на 43 окна, и 21 из них человек действительно переносил
    руками (треть всех его переносов). Двигать окно за него — нет: где именно
    звук, программа по уехавшим таймингам не знает.

    Если перенос всё же включён: двигается только окно, которое сейчас не глушит
    ничего; берётся БЛИЖАЙШИЙ участок речи (при равном расстоянии — более
    длинный) и только через тишину не шире `max_gap_ms`; длительность
    сохраняется, так что мьют не становится шире, чем решил ASR-путь. Клампы
    prev/next-word из `_compute_mute_window` перенос не удерживают — и не должны:
    если тайминги этого слова уехали, границы его соседей врут ровно так же.

    Правило, которое было с самого начала: если хоть один участок речи
    ПЕРЕСЕКАЕТСЯ с окном, окно считается стоящим на звуке (вердикт `"ok"`) — ни
    переноса, ни метки. Без этого правила окно, стоящее на тихом мате рядом с
    громким соседом, уезжало бы на соседа — ровно тот баг, из-за которого поиск
    речи в `trim_window` привязан к `cores` (см.
    test_trim_window_does_not_drift_onto_louder_neighbour).
    """
    if end_ms <= start_ms or threshold <= 0.0 or search_ms <= 0:
        return start_ms, end_ms, "ok"

    lo = max(0, start_ms - search_ms)
    frames, base_ms = energy.rms_frames(lo, end_ms + search_ms)
    if not frames:
        return start_ms, end_ms, "ok"
    lo_i = max(0, int((start_ms - base_ms) / FRAME_MS))
    hi_i = min(len(frames), int(math.ceil((end_ms - base_ms) / FRAME_MS)))
    if hi_i <= lo_i:
        return start_ms, end_ms, "ok"

    inside = frames[lo_i:hi_i]
    voiced = sum(1 for v in inside if v >= threshold) / len(inside)
    if voiced > max_voiced:
        return start_ms, end_ms, "ok"

    runs = _voiced_runs(frames, base_ms, threshold, min_ms=min_run_ms)
    if any(run[0] < end_ms and run[1] > start_ms for run in runs):
        # Речь задевает окно — звук в мьюте есть, он просто тише порога. Ни
        # двигать, ни помечать: уедем с тихого мата на громкого соседа.
        return start_ms, end_ms, "ok"
    if not runs:
        return start_ms, end_ms, "no_speech"
    if not move:
        # Пустое окно найдено, речь рядом есть — но переносить не велено:
        # вызывающий пометит окно и позовёт человека.
        return start_ms, end_ms, "silent"

    def distance(run: tuple[int, int]) -> int:
        if run[1] <= start_ms:
            return start_ms - run[1]
        return run[0] - end_ms

    # Ближайший участок; при равном расстоянии — более длинный (это скорее слово,
    # чем стук). Отрицательная длина в ключе = сортировка по убыванию.
    best = min(runs, key=lambda r: (distance(r), -(r[1] - r[0])))
    if distance(best) > max_gap_ms:
        # Речь есть, но за широкой тишиной: чей это звук — неизвестно, и мьют
        # там с той же вероятностью накроет чужое слово, что и нужное. Именно
        # такие переносы (зазор от 300 мс: «сука» +990 мс, «ебаный» +820,
        # «хули» −740) уводили мьют с мата.
        return start_ms, end_ms, "no_speech"

    duration = end_ms - start_ms
    new_start = max(0, best[0] - guard_ms)
    new_end = new_start + duration
    total = energy.duration_ms
    if total > 0 and new_end > total:
        new_end = total
        new_start = max(0, new_end - duration)
    if (new_start, new_end) == (start_ms, end_ms):
        return start_ms, end_ms, "ok"
    return int(new_start), int(new_end), "reanchored"


def open_energy(path: Path | None) -> WavEnergy | None:
    """Открыть кэш аудио для подгонки. Любая проблема — None: подгонка это
    улучшение точности, а не обязательный этап, и пайплайн из-за неё падать
    не должен.
    """
    if path is None:
        return None
    try:
        if not Path(path).exists():
            return None
        return WavEnergy(Path(path))
    except Exception as exc:
        logger.warning("Не удалось открыть аудио для подгонки мьютов (%s): %s", path, exc)
        return None
