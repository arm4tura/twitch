"""Подгонка границ мьюта по АУДИО, а не только по таймингам ASR.

ПРОБЛЕМА. Границы мьюта до этого считались целиком из транскрипта: начало
первого мата → конец последнего, плюс padding, плюс потолки. Аудио в этом
решении не участвовало ни разу. А ASR-тайминги врут двумя способами:

1. `timing_source == "segment_fallback"` — у слова нет своих таймингов, и оно
   наследует границы ВСЕГО VAD-сегмента (см. transcription.py).
2. whisper.cpp ставит последнему слову сегмента `end` = конец сегмента.

Оба случая ловились потолком `mute_max_word_seconds` (1.5 с) — но потолок это
ПОТОЛОК, а не подгонка: мьют получался ровно 1.5 + 0.12 + 0.08 = 1.70 с,
константной ширины, никак не связанной со звуком. Визуально — красная плита,
тянущаяся далеко по тишине после того, как звук затух.

РЕШЕНИЕ. Внутри уже посчитанного окна срезаем ТИШИНУ по краям — и только её.

ТОЛЬКО СУЖАЕМ. Расширять нельзя ни на миллисекунду: логика prev/next-word в
`_compute_mute_window` специально не даёт мьюту заехать на соседнее чистое
слово, и расширение по энергии её бы обнулило (соседнее слово — это тоже
энергия). Поэтому результат всегда лежит внутри исходного окна, и мат не может
стать менее замьюченным, чем решил ASR-путь.

ЗВУК В ОТСТУПЕ ОСТАЁТСЯ В МЬЮТЕ. От каждого края окна идём внутрь по тишине до
первого звука — и останавливаемся. Через звук поджатие не перескакивает. Раньше
речь искалась ВНУТРИ разметки слова (`cores`), и итог был «звук внутри разметки
± guard» — то есть весь padding выбрасывался. А padding существует ровно затем,
чтобы впитывать ошибку разметки: против независимой линейки (onset после паузы
≥150 мс, 5309 слов) сетка слов не имеет систематического сдвига, медиана 0 мс, но
квартили ±160 мс. Отличить «хвост мата за границей разметки» от «начала соседнего
слова» в энергии нельзя — а цена ошибки разная: слышный мат против замьюченного
слога соседа.

Замер на четырёх правленых записях (55 минут, 328 окон человека): старое правило
оставляло слышимыми 17.4 с звука, который человек заглушил, новое — 14.7 с,
и это ПОЛ (столько же остаётся слышным, если не поджимать вовсе). Окон,
замьюченных целиком по звуку, 197 из 328 вместо 177; на 15-минутной записи
70 из 142 вместо 50. Цена — 3.4 с лишнего замьюченного звука (14.3 → 17.7 с) и
одно съеденное чистое слово (50 → 51).

СВОЮ РАБОТУ ПОДЖАТИЕ ПРИ ЭТОМ ДЕЛАЕТ. Против «не поджимать вовсе» при той же
утечке: длительность мьютов 159.4 с вместо 176.1 (16.7 с плит по тишине), лишнего
звука 17.7 против 17.9, съеденных чистых слов 51 против 54.

ЧТО ОСТАЁТСЯ СЛЫШНО — И ЭТО УЖЕ НЕ ПРО ПОДЖАТИЕ. Утечка на полу, значит остаток
поджатием не лечится в принципе. Разбор остатка (62 окна, где слышно ≥100 мс,
медиана 160 мс): 48 окон и 7.5 с — «окно узко с ОДНОГО края на 100–300 мс», это
ручка `mute_padding_*`; 10 окон и 2.8 с — окно стоит не там (сдвинуто внутри
непрерывной речи, см. `reanchor_window`); 4 окна и 1.2 с — мьюта рядом нет вовсе,
то есть слово не нашёл детектор. Отступы теперь рабочая ручка (раньше поджатие их
съедало), и цена у неё видна: +100 мс с двух сторон — утечка 14.7 → 13.7 с ценой
+13 съеденных чистых слов на 55 минут, +300 мс — 12.5 с ценой +58 слов. Класс
«узко» перекошен влево: +100 мс только слева даёт почти то же (14.0 с) за +10
слов. Числа уровней при этом трогать не стали: пока padding выбрасывался, их
подбирали при неработающем механизме, и переподбор — отдельное решение с ценой в
съеденной чистой речи (`SENSITIVITY_LEVELS`).

Внутрь разметки слова поджатие всё же заходит — но только по тишине, и это
обязательно: у слова без своих таймингов (`timing_source == "segment_fallback"`)
разметка сама по себе плита на `mute_max_word_seconds`, и звук в ней занимает
треть.

ПОРОГ СЧИТАЕТСЯ ПО БЛИЖАЙШЕМУ СЛОВУ. Вопрос у краёв один: «это тишина?» —
и мерка для него берётся от того слова, к которому край примыкает. Порог от пика
ВСЕГО окна на этом месте врал: громкий сосед в padding задирал его выше энергии
самого мата (так уехало 10 мьютов из 133), а порог от пика всего разбега группы
глушил тихое слово рядом с громким («блять» 337.8, «бля» 521.1, «сука» 656.6).
Именно порог по слову, а не запрет заходить в слово, и делает оба этих бага
невозможными.

ДВА ПОРОГА, И ЭТО НАМЕРЕННО. `trim_window` считает порог ОТНОСИТЕЛЬНО пика
слова — только так можно отличить тишину и рядом с криком, и рядом с тихим
бормотанием. Но у относительного порога есть слепое пятно: если в границах слова
вообще нет речи, пиком становится шум, порог падает под него, и «речь находится»
в тишине. Поэтому рядом живёт `global_threshold` — абсолютный уровень «тут
вообще есть звук», снятый редкими пробами по всему файлу. Это единственный
способ спросить «а есть ли здесь звук в принципе»; им пользуются и отчёт
(`audit.find_holes`), и `reanchor_window`. Ограничить порог поджатия абсолютным
пробовали — на тех же четырёх записях это не меняет ничего (17.4 → 17.4 с):
терялся не тихий край слова, а именно padding.

ПЕРЕНОС ОКНА (`reanchor_window`) — отдельная операция, и по умолчанию она НЕ
ДВИГАЕТ окно, а лишь помечает пустое окно на проверку человеком. Правило «только
сужаем» на неё не распространяется: переносится окно, которое НЕ ГЛУШИТ НИЧЕГО —
тайминги слова у ASR уехали в тишину, и мат остался слышен целиком. Замер на
vod_2847020280: «бля» 261.612–261.971 — 0% озвученных кадров по абсолютному
порогу при score выравнивания 0.9988, реальный звук на 262.192–262.442, человек
руками сдвинул мьют на +543 мс (аудио просит +580 мс). Поджатие тут не спасало и
не могло: оно ещё и сузило окно на 140 мс ВНУТРИ шума.

Но на двух записях подольше тот же перенос увёл мьют с мата 10 раз при 2
попаданиях, и ни одно ограничение этого не исправило (полный разбор — в docstring
`reanchor_window`). Причина в самом признаке: абсолютный порог равен уровню
громкой речи, поэтому ТИХИЙ мат под ним выглядит тишиной, и «пустое» окно на
самом деле стоит на звуке. Поэтому решение о переносе теперь за человеком
(`mute_reanchor_move`), а программа только показывает ему такие окна.
"""

