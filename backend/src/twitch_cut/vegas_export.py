from __future__ import annotations

from pathlib import Path
from typing import Any


class VegasExportError(ValueError):
    """Raised when decisions.json cannot be exported to Vegas script."""




def exportable_mutes(decisions: dict[str, Any]) -> list[dict[str, Any]]:
    """Return editable mute decisions that should become Vegas audio edits."""

    mutes = decisions.get("mutes")
    if mutes is None:
        raise VegasExportError("decisions.json must contain a 'mutes' array")
    if not isinstance(mutes, list):
        raise VegasExportError("decisions.json field 'mutes' must be an array")

    result: list[dict[str, Any]] = []
    for index, mute in enumerate(mutes):
        if not isinstance(mute, dict):
            raise VegasExportError(f"mutes[{index}] must be an object")
        if mute.get("action", "MUTE") != "MUTE":
            continue
        if mute.get("status", "accepted") in {"rejected", "deleted", "disabled", "review"}:
            continue
        if "stream_start" not in mute or "stream_end" not in mute:
            raise VegasExportError(f"mutes[{index}] must contain stream_start and stream_end")
        start = float(mute["stream_start"])
        end = float(mute["stream_end"])
        if end <= start:
            raise VegasExportError(f"mutes[{index}] has stream_end <= stream_start")
        result.append(mute)
    return result


def generate_vegas_script(decisions: dict[str, Any]) -> str:
    """Generate a Vegas Pro C# script that mutes profanity ranges.

    Design decisions (важно, не менять без нужды):
      - Никаких Region'ов / Marker'ов: пользователь просил чистый timeline.
      - Мут делаем НЕ через свойство ``TrackEvent.Mute = true`` (это ставит флаг
        на весь клип), а через splice + ``FadeIn.Gain = 0``: разрезаем событие
        на границах диапазона и у среднего кусочка опускаем гейн фейда в 0
        (эквивалент абсолютной тишины на этом фрагменте).
      - После обработки перегруппировываем события: аудио- и видео-событие с
        (почти) одинаковым Start попадают в один ``TrackEventGroup``, чтобы
        нарезка не разъезжалась при последующем drag'n'drop'е.

    Итог: тот же аудиофайл, но каждый profanity-диапазон разрезан на 3 события;
    среднее — с ``FadeIn.Gain = 0`` (тишина). Парные события (аудио+видео)
    склеены обратно в единые группы.
    """

    lines = [
        "// Generated by twitch_cut Phase 5.",
        "// Splits audio events at profanity boundaries and silences the middle",
        "// piece by dropping its gain to 0. Groups all resulting tracks into one",
        "// TrackGroup. Does NOT create regions or markers.",
        "using System;",
        "using System.Collections.Generic;",
        "using ScriptPortal.Vegas;",
        "",
        "public class EntryPoint",
        "{",
        "    public void FromVegas(Vegas vegas)",
        "    {",
    ]

    mutes = exportable_mutes(decisions)
    for mute in mutes:
        start = float(mute["stream_start"])
        end = float(mute["stream_end"])
        lines.append(f"        SilenceAudioRange(vegas, {start:.3f}, {end:.3f});")

    # Regroup — после всех разрезов, чтобы новые события тоже попали в группы.
    lines.append("        RegroupPairs(vegas);")

    lines.extend(
        [
            "    }",
            "",
            "    private void SilenceAudioRange(Vegas vegas, double start, double end)",
            "    {",
            "        foreach (Track track in vegas.Project.Tracks)",
            "        {",
            "            List<TrackEvent> evs = new List<TrackEvent>();",
            "            foreach (TrackEvent e in track.Events) evs.Add(e);",
            "",
            "            foreach (TrackEvent e in evs)",
            "            {",
            "                double es = e.Start.ToMilliseconds() / 1000.0;",
            "                double ee = e.End.ToMilliseconds() / 1000.0;",
            "                if (ee <= start || es >= end) continue;",
            "",
            "                TrackEvent mid = e;",
            "                if (es < start) mid = e.Split(Timecode.FromSeconds(start - es));",
            "                ",
            "                double ms = mid.Start.ToMilliseconds() / 1000.0;",
            "                double me = mid.End.ToMilliseconds() / 1000.0;",
            "                if (me > end) mid.Split(Timecode.FromSeconds(end - ms));",
            "",
            "                // Старый добрый способ проверки типа без 'is'",
            "                AudioEvent ae = mid as AudioEvent;",
            "                if (ae != null)",
            "                {",
            "                    ae.FadeIn.Gain = 0f;",
            "                }",
            "            }",
            "        }",
            "    }",
            "",
            "    private void RegroupPairs(Vegas vegas)",
            "    {",
            "        vegas.Project.Groups.Clear();",
            "        var evs = new List<TrackEvent>();",
            "        foreach (Track t in vegas.Project.Tracks)",
            "            foreach (TrackEvent e in t.Events) evs.Add(e);",
            "        evs.Sort((a, b) => a.Start.CompareTo(b.Start));",
            "        for (int i = 0; i < evs.Count; i++)",
            "        {",
            "            for (int j = i + 1; j < evs.Count; j++)",
            "            {",
            "                if (evs[j].Start.ToMilliseconds() - evs[i].Start.ToMilliseconds() >= 10) break;",
            "                if (evs[i].Track == evs[j].Track) continue;",
            "                TrackEventGroup g = new TrackEventGroup();",
            "                vegas.Project.Groups.Add(g);",
            "                g.Add(evs[i]);",
            "                g.Add(evs[j]);",
            "            }",
            "        }",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def write_vegas_script(path: Path, decisions: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_vegas_script(decisions), encoding="utf-8")


# --- highlights markers ------------------------------------------------------
#
# Отдельный скрипт от mute-скрипта: тот сознательно НЕ ставит маркеры («чистый
# timeline»). Здесь наоборот — highlights это навигация по ярким моментам, и
# маркеры/регионы Vegas ровно для этого. Не мешаем два в одном: пользователь
# запускает нужный скрипт под задачу.


def exportable_highlights(decisions: dict[str, Any]) -> list[dict[str, Any]]:
    """Вернуть highlights, пригодные для маркеров Vegas (в stream-секундах).

    Highlights лежат под ключом 'highlights' как bundle {highlights: [...]}.
    Берём каждый с stream_start_s/stream_end_s (их проставляет merge_into_
    decisions). Фолбэк на start_s/end_s (локальные) — если merge был старой
    версии; лучше сдвинутый маркер, чем пустой экспорт.
    """
    bundle = decisions.get("highlights") or {}
    items = bundle.get("highlights") if isinstance(bundle, dict) else None
    if not items:
        raise VegasExportError("decisions.json не содержит highlights для экспорта")

    result: list[dict[str, Any]] = []
    for index, h in enumerate(items):
        if not isinstance(h, dict):
            raise VegasExportError(f"highlights[{index}] must be an object")
        start = h.get("stream_start_s", h.get("start_s"))
        end = h.get("stream_end_s", h.get("end_s"))
        if start is None or end is None:
            raise VegasExportError(f"highlights[{index}] missing start/end")
        if float(end) <= float(start):
            raise VegasExportError(f"highlights[{index}] has end <= start")
        result.append(h)
    return result


def _escape_cs(text: str) -> str:
    """Экранировать строку для C# literal (кавычки/бэкслеши/переносы)."""
    return (
        text.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\r", " ")
        .replace("\n", " ")
    )


def generate_vegas_highlights_script(decisions: dict[str, Any]) -> str:
    """C#-скрипт для Vegas: ставит Region на каждый highlight (нарезка моментов).

    В отличие от mute-скрипта, здесь только Regions — они видны на таймлайне и в
    списке регионов Vegas, по ним удобно прыгать и рендерить куски (Render
    Regions). Имя региона = "★ score title".
    """
    highlights = exportable_highlights(decisions)

    lines = [
        "// Generated by twitch_cut — highlights markers.",
        "// Adds one Region per highlight for quick navigation / region render.",
        "using System;",
        "using ScriptPortal.Vegas;",
        "",
        "public class EntryPoint",
        "{",
        "    public void FromVegas(Vegas vegas)",
        "    {",
    ]
    for h in highlights:
        start = float(h.get("stream_start_s", h.get("start_s")))
        end = float(h.get("stream_end_s", h.get("end_s")))
        score = h.get("score")
        title = str(h.get("title", "highlight"))
        label = f"★ {score:.2f} {title}" if isinstance(score, (int, float)) else f"★ {title}"
        label = _escape_cs(label)[:120]
        lines.append(
            f"        AddRegion(vegas, {start:.3f}, {end - start:.3f}, \"{label}\");"
        )
    lines.extend(
        [
            "    }",
            "",
            "    private void AddRegion(Vegas vegas, double start, double length, string label)",
            "    {",
            "        Timecode s = Timecode.FromSeconds(start);",
            "        Timecode len = Timecode.FromSeconds(length);",
            "        vegas.Project.Regions.Add(new Region(s, len, label));",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def write_vegas_highlights_script(path: Path, decisions: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(generate_vegas_highlights_script(decisions), encoding="utf-8")
