/**
 * muteGain — громкость превью «как в экспорте» в конкретный момент времени.
 *
 * Экспорт глушит окно ЖЁСТКО (`volume=enable='between(t,a,b)':volume=0`, см.
 * backend render.py), а превью в «Правках» ведёт гейн живого <audio> из rAF, где
 * мгновенный скачок 1→0 слышен щелчком. Поэтому рампа есть — но она лежит
 * СНАРУЖИ окна: внутри [a,b) ровно ноль, спуск 1→0 успевает закончиться до `a`,
 * подъём 0→1 начинается после `b`. Тогда «заглушено на графике» и «заглушено на
 * слух» — одно и то же.
 *
 * Так было не всегда: рампа шла ВНУТРЬ окна от его края, то есть на самой
 * границе гейн был ещё 1.0, а ноль наступал через 45 мс. Обоснованием служило
 * «рампа умещается в паддинг мьюта (80/120 мс)», но подгонка по звуку
 * (mute_refine) поджимает окно к речи и паддинг съедает: на реальном прогоне 15
 * минут между краем окна и первым звуком ВНУТРИ него оставалось 0 мс (медиана;
 * 105 окон из 158 поджаты в среднем на 136 мс). Рампа шла по самому мату — через
 * превью просачивалось 21% амплитуды окна (медиана; по энергии 4.3%, в худшем
 * случае 71% и 50%), начало слова звучало на −7.2 дБ от пика мьюта. Слышно это
 * было как «мьют опаздывает», и человек сдвигал границу раньше — уже в настоящие
 * тайминги, которые уходят в рендер.
 *
 * ЧЕМ ПЛАТИМ. Рампа снаружи придушивает 45 мс ПЕРЕД окном и 45 мс ПОСЛЕ — это
 * край соседнего слова. На том же прогоне из 308 плеч 191 (62%) содержат хотя бы
 * один кадр речи, уровень плеча медианой −12.3 дБ от пика мьюта. То есть цена
 * реальна, но это фейд на чужом слове ТОЛЬКО в превью — экспорт по-прежнему
 * жёсткий гейт без фейдов. Обратный выбор (рампа внутрь) стоил мата в превью.
 *
 * Длина рампы задана не вкусом, а частотой rAF: гейн меняется раз в кадр, при 60
 * Гц кадр = 16.7 мс, на 45 мс приходится ~3 шага — спуск не слышен ступенькой.
 * Короче нельзя: одного-двух шагов 1→0 хватает ровно на тот щелчок, от которого
 * рампа и защищает. Остаточный шаг на последнем кадре перед `a` всё равно есть
 * (гейн там 0…0.33) — убрать его и заодно укоротить плечи до ~5 мс может только
 * сэмпл-точная автоматизация гейна в WebAudio (setValueCurveAtTime), а она
 * требует прокинуть <audio> через MediaElementAudioSourceNode с CORS.
 */
export const MUTE_RAMP_S = 0.045;

/** Заглушённое окно в audio-секундах: [начало, конец). */
export type MuteRegion = readonly [number, number];

/**
 * Гейн <audio> в момент `t` (audio-секунды) для набора заглушённых окон.
 *
 * Берётся МИНИМУМ по окнам: два мьюта рядом (щель уже 2×ramp) не должны пускать
 * громкость обратно вверх между собой — иначе в щели прозвучит ровно то, что оба
 * окна и глушат. `regions` ожидаются отсортированными по началу: тогда скан
 * прекращается на первом окне, которое правее рампы.
 */
export function muteGainAt(
  t: number,
  regions: readonly MuteRegion[],
  ramp: number = MUTE_RAMP_S
): number {
  let gain = 1;
  for (const [a, b] of regions) {
    if (t >= b + ramp) continue; // окно целиком позади
    if (t < a - ramp) break; // дальше окна только правее — они уже не влияют
    let g: number;
    if (t >= a && t < b) {
      g = 0; // внутри окна — ровно как в экспорте
    } else if (t < a) {
      g = ramp > 0 ? (a - t) / ramp : 0; // спуск, заканчивается в `a`
    } else {
      g = ramp > 0 ? (t - b) / ramp : 0; // подъём, начинается в `b`
    }
    if (g < gain) gain = g;
    if (gain <= 0) return 0;
  }
  return gain;
}
